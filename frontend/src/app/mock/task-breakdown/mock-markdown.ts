/**
 * Stream by whole `### Agent` blocks so the parser can fill cards progressively.
 * (Character chunks often split `###` across slices — then nothing parses until the very end.)
 */
export function mockMarkdownChunks(): string[] {
  const full = MOCK_TASK_BREAKDOWN_FULL.trim();
  const blocks = full.split(/(?=^### )/m).filter((b) => b.length > 0);
  if (blocks.length === 0) {
    return [full];
  }
  const chunks: string[] = [];
  for (let i = 0; i < blocks.length; i++) {
    chunks.push(blocks.slice(0, i + 1).join(""));
  }
  return chunks;
}
